package dev.halyx.spring.data.document;

import java.lang.annotation.Documented;
import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * The {@code DocumentStore} bean an entity is stored in, such as one of {@code halyx.document-stores}. May be left
 * out when the application has exactly one {@code DocumentStore} bean.
 */
@Documented
@Retention(RetentionPolicy.RUNTIME)
@Target(ElementType.TYPE)
public @interface DocumentTable {

    /** The {@code DocumentStore} bean name. */
    String value();
}
